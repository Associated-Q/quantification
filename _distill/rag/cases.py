def label_of_parent(parent):
    """把检索命中的父块映射到评测标签。

    书籍按 book 前缀映射到 b1..b5，凯利公式小册子映射到 kelly；
    qa/comment/community 按 parent_id 的前两段归并同一问答/主评论的所有分块。
    """
    src = parent.get("source", "book")
    if src == "book":
        book = parent.get("book") or ""
        m = re.match(r"(b\d+)", book)
        if m:
            return m.group(1)          # b1..b10，按编号归类
        if str(parent.get("parent_id", "")).startswith("book#kelly"):
            return "kelly"
        return "book_other"
    if src in ("qa", "comment", "community"):
        parts = str(parent.get("parent_id", "")).split("#")
        if len(parts) >= 2:
            return f"{src}#{parts[1]}"
    return src


def stratum_of(ok):
    """返回用例所属层级：book / qa_comment / other。"""
    ok = set(ok)
    if ok <= BOOK_LABELS:
        return "book"
    if all(label.startswith(("qa#", "comment#")) for label in ok):
        return "qa_comment"
    return "other"
